"""Q-16: the note's tables (`docs/research/calibration_2026-11-15.md`), printed as markdown from the calibration's own
CSVs (`scripts/q16_calibrate.py --out <dir>`): every figure in the note's tables is regenerated by this script, none is
typed. EXPLORATORY; writes nothing but `<dir>/tables.md`.

    python scripts/q16_tables.py --dir <dir>

The tables: (1) the lift's worst realised level by candidate and family level, over the real nulls, the realistic
synthetic nulls and the stress nulls, with the null that attains it and its 95 % Clopper-Pearson interval; (2) the
lift's rates at 0.05/132 on the main real nulls; (3) the bootstrap's rows; (4) the lift's minimum detectable lift at
80 % power by trade count; (5) the P comparison's worst realised level by candidate; (6) its minimum detectable
difference on the judged block.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from extended import lift_bound as LB  # noqa: E402

STRESS = ("syn:cluster_ar5", "syn:regime03", "syn:regime10", "syn:skew")
KS = list(LB.K_RANGE)


def _fmt_rate(r: float) -> str:
    return f"{r * 1e4:.2f}"


def worst_table(size: pd.DataFrame, methods, groups) -> str:
    """Per method and k: the largest rate / nominal over each group's nulls, '(null; rate x 1e4 [ci])'."""
    rows = ["| method | nulls | " + " | ".join(f"k = {k} (nominal {LB.family_level(k) * 1e4:.2f})" for k in KS) + " |",
            "|---|---|" + "---|" * len(KS)]
    for m in methods:
        for gname, mask in groups:
            g = size[(size["method"] == m) & mask]
            if g.empty:
                continue
            cells = []
            for k in KS:
                gk = g[g["k"] == k]
                if gk.empty:
                    cells.append("--")
                    continue
                r = gk.loc[gk["ratio"].idxmax()]
                cells.append(f"**{r['ratio']:.2f}x** ({_fmt_rate(r['rate'])} [{_fmt_rate(r['ci_lo'])}, "
                             f"{_fmt_rate(r['ci_hi'])}]; {r['null']})")
            rows.append(f"| `{m}` | {gname} ({g['null'].nunique()}) | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def share_table(size: pd.DataFrame, methods, groups, k: int = 11) -> str:
    """Per method: the share of nulls whose 95 % interval lies wholly above the nominal rate at family k."""
    rows = ["| method | " + " | ".join(f"{g} (nulls)" for g, _ in groups) + " |", "|---|" + "---|" * len(groups)]
    for m in methods:
        cells = []
        for _, mask in groups:
            g = size[(size["method"] == m) & mask & (size["k"] == k)]
            above = int((g["ci_lo"] > g["level"]).sum())
            cells.append(f"{above} of {len(g)}")
        rows.append(f"| `{m}` | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def rate_table(size: pd.DataFrame, nulls, methods, k: int = 11) -> str:
    rows = ["| null | " + " | ".join(f"`{m}`" for m in methods) + " |", "|---|" + "---|" * len(methods)]
    for nl in nulls:
        g = size[(size["null"] == nl) & (size["k"] == k)]
        if g.empty:
            continue
        cells = []
        for m in methods:
            r = g[g["method"] == m]
            cells.append("--" if r.empty else f"{_fmt_rate(float(r['rate'].iloc[0]))} ({float(r['ratio'].iloc[0]):.2f}x)")
        rows.append(f"| {nl} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def boot_table(boot: pd.DataFrame) -> str:
    rows = ["| null | reps | draws | k = 11: rejections (rate x 1e4, ratio) | `t21w` on the same replications | k = 15 | "
            "crit / t crit at k = 11 (p10, p50, p90) |", "|---|---|---|---|---|---|---|"]
    for nl, g in boot.groupby("null", sort=False):
        r11 = g[g["k"] == 11].iloc[0]
        r15 = g[g["k"] == 15].iloc[0]
        rows.append(f"| {nl} | {int(r11['reps'])} | {int(r11['draws'])} | {int(r11['rejections'])} "
                    f"({_fmt_rate(r11['rate'])}, {r11['ratio']:.2f}x) | {int(r11['t21w_same_reps'])} | "
                    f"{int(r15['rejections'])} ({r15['ratio']:.2f}x) | {r11['crit_over_t_p10']:.3f}, "
                    f"{r11['crit_over_t_p50']:.3f}, {r11['crit_over_t_p90']:.3f} |")
    return "\n".join(rows)


def power_table(power: pd.DataFrame, base: str, value: str, methods, scale: float, unit: str) -> str:
    """MDL80 (and MDL50) at k = 11 and 15 on the real thinned streams of one side model, by trade count."""
    rows = [f"| trades | " + " | ".join(f"`{m}` k=11 | `{m}` k=15" for m in methods) + " |",
            "|---|" + "---|" * (2 * len(methods))]
    for n in (200, 500, 1000, 2000, 5000):
        nl = f"real:thin{n}:{value}:{base}"
        g = power[power["null"] == nl]
        if g.empty:
            continue
        cells = []
        for m in methods:
            for k in (11, 15):
                r = g[(g["method"] == m) & (g["k"] == k)]
                cells.append("--" if r.empty else f"{float(r['mdl80'].iloc[0]) * scale:.{1 if scale > 1 else 3}f}")
        rows.append(f"| {n} | " + " | ".join(cells) + " |")
    return f"(80 % power; {unit})\n\n" + "\n".join(rows)


def p_power_table(pp: pd.DataFrame, nulls, methods) -> str:
    rows = ["| null | " + " | ".join(f"`{m}` k=11 | `{m}` k=15" for m in methods) + " |",
            "|---|" + "---|" * (2 * len(methods))]
    for nl in nulls:
        g = pp[pp["null"] == nl]
        cells = []
        for m in methods:
            for k in (11, 15):
                r = g[(g["method"] == m) & (g["k"] == k)]
                cells.append("--" if r.empty else f"{float(r['mdd80'].iloc[0]):.3f}")
        rows.append(f"| {nl} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


#: Q-55's result files (`scripts/q55_calibration.py`) and how they split back into the calibration's part CSVs
RESULT_FILES = ("calibration_lift", "calibration_p", "calibration_two_sample", "calibration_power", "bm63c_table")


def _verified(path: Path) -> pd.DataFrame:
    """A result CSV after its manifest's sha256 check (the vendored writer's manifest; no vendored import here)."""
    man = json.loads(Path(f"{path}.manifest.json").read_text(encoding="utf-8"))
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    if got != man["sha256"]:
        raise SystemExit(f"REFUSED: {path} does not match its manifest's sha256 ({got[:12]} against "
                         f"{man['sha256'][:12]})")
    return pd.read_csv(path, low_memory=False)


def split_results(results: Path, into: Path) -> list[Path]:
    """Write the part CSVs the tables read (lift/, p/, select/, select_all/) from the five result files."""
    r = {n: _verified(Path(results) / f"{n}.csv") for n in RESULT_FILES}
    drop = lambda df: df.dropna(axis=1, how="all")                      # noqa: E731
    parts = {"lift": {"lift_size.csv": r["calibration_lift"].query("section == 'size'"),
                      "lift_boot.csv": r["calibration_lift"].query("section == 'boot'"),
                      "lift_power.csv": r["calibration_power"].query("part == 'lift'")},
             "p": {"p_size.csv": r["calibration_p"], "p_power.csv": r["calibration_power"].query("part == 'p'"),
                   "p_bm63c_critical.csv": r["bm63c_table"]}}
    for rule, sub in (("treated", "select"), ("all", "select_all")):
        two = r["calibration_two_sample"]
        pw = r["calibration_power"]
        if (two["df_rule"] == rule).any():
            parts[sub] = {"diff_size.csv": two[two["df_rule"] == rule],
                          "diff_power.csv": pw[(pw["part"] == "two_sample") & (pw["df_rule"] == rule)]}
    out = []
    for sub, files in parts.items():
        dd = Path(into) / sub
        dd.mkdir(parents=True, exist_ok=True)
        for f, df in files.items():
            drop(df).to_csv(dd / f, index=False)
        out.append(dd)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--dir", type=Path, help="a calibration output folder (scripts/q16_calibrate.py --out)")
    g.add_argument("--results", type=Path, help="a folder holding Q-55's five result files")
    a = ap.parse_args(argv)
    if a.results is not None:
        import tempfile
        with tempfile.TemporaryDirectory(prefix="q16_tables_") as tmp:
            texts = []
            import contextlib
            import io
            for dd in split_results(a.results, Path(tmp)):
                with contextlib.redirect_stdout(io.StringIO()):
                    main(["--dir", str(dd)])
                txt = (dd / "tables.md").read_text(encoding="utf-8")
                texts.append(txt.replace("Table ", "Table F") if dd.name == "select_all" else txt)
        print("\n\n".join(texts))
        return 0
    d = Path(a.dir)
    out = []
    if (d / "lift_size.csv").is_file():
        size = pd.read_csv(d / "lift_size.csv")
        power = pd.read_csv(d / "lift_power.csv")
        real = size["null"].str.startswith("real:")
        stress = size["null"].str.startswith(STRESS)
        syn = size["null"].str.startswith("syn:") & ~stress
        methods = ["t21e", "t21w", "t42w", "t63w", "hac21", "cons"]
        groups = [("real", real), ("synthetic", syn), ("stress", stress)]
        out += ["## Table 1. The lift: the worst realised level (rate / nominal) by candidate, family level and null group",
                "", "Rates x 1e4 with the 95 % Clopper-Pearson interval; the null that attains the maximum.", "",
                worst_table(size, methods, groups), "",
                "### Table 1b. Nulls whose 95 % interval lies wholly above the nominal rate (k = 11)", "",
                share_table(size, methods, groups), ""]
        main_nulls = [f"real:{s}:{v}:{side}" for s in ("taken", "thin200", "thin1000", "thin5000", "offered")
                      for v in ("win1", "net3") for side in ("persist1", "persist21", "persist63", "coin")]
        out += ["## Table 2. The lift: rates x 1e4 at 0.05/132 (ratio to nominal) on the main real nulls", "",
                rate_table(size, main_nulls, methods), ""]
        if (d / "lift_boot.csv").is_file():
            out += ["## Table 3. The studentised circular block bootstrap (`cbb21`)", "",
                    boot_table(pd.read_csv(d / "lift_boot.csv")), ""]
        for base in ("coin", "persist1"):
            out += [f"## Table 4{'a' if base == 'coin' else 'b'}. The lift's minimum detectable lift at 80 % power, "
                    f"real {base} nulls thinned to N trades", "",
                    power_table(power, base, "win1", ["t21w", "t63w", "cons"], 100.0,
                                "win probability, points (x 100)"), "",
                    power_table(power, base, "net3", ["t21w", "t63w", "cons"], 1.0, "net R at 3R"), ""]
    if (d / "p_size.csv").is_file():
        ps = pd.read_csv(d / "p_size.csv")
        pp = pd.read_csv(d / "p_power.csv")
        real = ps["null"].str.startswith("real:")
        syn = ps["null"].str.startswith("syn:") & ~ps["null"].isin(["syn:path_edge"])
        stress = ps["null"].isin(["syn:path_edge"])
        pm = ["d621", "bm63", "bm126", "obm63", "obm126", "ft63", "pcons", "bm63c"]
        out += ["## Table 5. The P comparison: the worst realised level by candidate, family level and null group", "",
                worst_table(ps, pm, [("real", real), ("synthetic", syn), ("stress", stress)]), "",
                "### Table 5b. Nulls whose 95 % interval lies wholly above the nominal rate (k = 11)", "",
                share_table(ps, pm, [("real", real), ("synthetic", syn), ("stress", stress)]), ""]
        out += ["## Table 6. The P comparison's minimum detectable difference in P at 80 % power, judged block", "",
                p_power_table(pp, ["real:p16v-p14v:centred:flip63", "real:p16v-p14v:centred:flip21",
                                   "real:p14p-p14v:centred:flip63", "real:p16p-p16v:centred:flip63"],
                              ["bm63", "bm126", "ft63", "pcons", "bm63c"]), ""]
        if (d / "p_bm63c_critical.csv").is_file():
            c = pd.read_csv(d / "p_bm63c_critical.csv")
            rows = ["| level | k | `bm63c` critical value | t(8)'s | ratio | attained on | calibration nulls x replications |",
                    "|---|---|---|---|---|---|---|"]
            for _, r in c.iterrows():
                kk = "" if pd.isna(r["k"]) else str(int(r["k"]))
                rows.append(f"| {r['level']:.3g} | {kk} | {r['critical']:.3f} | {r['t8']:.3f} | {r['ratio_to_t8']:.3f} | "
                            f"{r['argmax_null']} | {int(r['calibration_nulls'])} x {int(r['reps_each'])} |")
            out += ["## Table 7. `bm63c`: the batch-means t's critical values calibrated on the declared nulls (stage 1)",
                    "", "\n".join(rows), ""]
    if (d / "diff_size.csv").is_file():
        ds = pd.read_csv(d / "diff_size.csv")
        dp = pd.read_csv(d / "diff_power.csv")
        dm = ["t21w", "t42w", "t63w", "cons"]
        sel = ds["form"] == "placebo-selection"
        c1p = ds["form"] == "two-sample (C1')"
        groups = [(f"selection: {m}", sel & (ds["model"] == m)) for m in ("offer", "window", "session", "block5",
                                                                           "block21", "block63")]
        out += ["## Table 8. The placebo-selection twin (E-023): the worst realised level by selection model", "",
                "Random filters independent of the outcomes, firing on 2 % to 50 % of P-16's judged offers; the "
                "selected offers' own outcome against every offer's (the twin's expectation).", "",
                worst_table(ds, dm, groups), "",
                "### Table 8b. Nulls whose 95 % interval lies wholly above the nominal rate (k = 11)", "",
                share_table(ds, dm, groups), ""]
        rows = ["| model | value | share | `t21w` k=11 | `cons` k=11 | `cons` k=15 |", "|---|---|---|---|---|---|"]
        pp = dp[dp["form"] == "placebo-selection"]
        for (mo, v, sh), g in pp.groupby(["model", "value", "share"], sort=False):
            def cell(m, k):
                r = g[(g["method"] == m) & (g["k"] == k)]
                x = float(r["difference80"].iloc[0]) if len(r) else float("nan")
                return "--" if not np.isfinite(x) else (f"{x * 100:.1f}" if v == "win1" else f"{x:.3f}")
            rows.append(f"| {mo} | {v} | {sh:g} | {cell('t21w', 11)} | {cell('cons', 11)} | {cell('cons', 15)} |")
        out += ["## Table 9. The placebo-selection twin: the selected-minus-twin difference detectable at 80 % power, "
                "by firing share", "", "(win1 in points of win probability; net3 in R; -- where 80 % is not reached "
                "inside the grid)", "", "\n".join(rows), ""]
        groups2 = [(f"C1': {m}", c1p & (ds["model"] == m)) for m in ("shared", "indep", "coin")]
        out += ["## Table 10. F-02's C1' (E-022), the level lift minus the placebo lift: the worst realised level", "",
                worst_table(ds, dm, groups2), "",
                "### Table 10b. Nulls whose 95 % interval lies wholly above the nominal rate (k = 11)", "",
                share_table(ds, dm, groups2), ""]
        rows = ["| level fills | value | sides | `t21w` k=11 | `cons` k=11 | `cons` k=15 |", "|---|---|---|---|---|---|"]
        pc = dp[(dp["form"] == "two-sample (C1')") & (dp["model"].isin(["shared", "indep"])) & (dp["L"] == 1)]
        for (n1, v, mo), g in pc.groupby(["level_fills", "value", "model"], sort=False):
            def cell2(m, k):
                r = g[(g["method"] == m) & (g["k"] == k)]
                x = float(r["difference80"].iloc[0])
                return f"{x * 100:.1f}" if v == "win1" else f"{x:.3f}"
            rows.append(f"| {int(n1)} | {v} | {mo} | {cell2('t21w', 11)} | {cell2('cons', 11)} | {cell2('cons', 15)} |")
        out += ["## Table 11. C1': the difference D detectable at 80 % power (placebo fills five times the level's; "
                "sides flipped by session)", "", "\n".join(rows), ""]
    txt = "\n".join(out)
    (d / "tables.md").write_text(txt, encoding="utf-8")
    print(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
